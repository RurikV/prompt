nb = nbformat.read("hw_prompt_sentiment.ipynb", as_version=4)
replaced = []
for idx, cell in enumerate(nb.cells):
    if cell.cell_type != "markdown":
        continue
    for marker, text in FILLS.items():
        if cell.source.startswith(marker):
            cell.source = text.strip()
            replaced.append(marker.strip("<>!-").replace("FILL:", ""))
nbformat.write(nb, "hw_prompt_sentiment.ipynb")
print(f"заменено аналитических ячеек: {len(replaced)} из {len(FILLS)}: {replaced}")
